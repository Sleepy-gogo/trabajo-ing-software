export function getUserById(id: string): User | undefined {
  return users.find((user) => user.id === id)
}

export function getMembershipByUserId(userId: string): Membership | undefined {
  return memberships.find((membership) => membership.userId === userId)
}

export function getPaymentsByUserId(userId: string): Payment[] {
  return payments.filter((payment) => payment.userId === userId)
}

export function getSpaceById(id: string): Space | undefined {
  return spaces.find((space) => space.id === id)
}

export function getAvailabilityForSpace(
  spaceId: string,
  date?: string
): AvailabilityDay[] {
  const days = availabilityBySpace[spaceId] ?? []
  return date ? days.filter((day) => day.fecha === date) : days
}

export function getReservationsByUserId(userId: string): Reservation[] {
  return reservations.filter((reservation) => reservation.userId === userId)
}

export function getReservationById(id: string): Reservation | undefined {
  return reservations.find((reservation) => reservation.id === id)
}

export function getTicketById(id: string): ReservationTicket | undefined {
  return tickets.find((ticket) => ticket.id === id)
}

export function getTicketsByUserId(userId: string): ReservationTicket[] {
  return tickets.filter((ticket) => ticket.userId === userId)
}

export function getAccessRecordsByUserId(userId: string): AccessRecord[] {
  return accessRecords.filter((record) => record.userId === userId)
}

export function getSurveyById(id: string): Survey | undefined {
  return surveys.find((survey) => survey.id === id)
}

export function getReportsByType(type: Report["tipo"]): Report[] {
  return reports.filter((report) => report.tipo === type)
}

export function getReportById(id: string): Report | undefined {
  return reports.find((report) => report.id === id)
}
